    local function applyVideoSpeed()
        if vMediaPlayer == nil then return end
        if math.abs(VP.speed - 1.0) < 0.01 then return end
        local ok = pcall(function()
            local params = vMediaPlayer.getPlaybackParams()
            params.setSpeed(VP.speed)
