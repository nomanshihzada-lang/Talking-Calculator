-- ===== Lyrics (.lrc) =====
-- Gaane ki path se ".mp3"/".m4a" waghera hata ke ".lrc" try karta hai (same naam, same folder)
function MP.parseLrcForSong(songPath)
    MP.lyricsLines = {}
    MP.lyricsSongPath = songPath
    if not songPath then return end
    local lrcPath = songPath:gsub("%.[%a%d]+$", ".lrc")
    local f = io.open(lrcPath, "r")
    if not f then return end
    for line in f:lines() do
        for min, sec, hun, text in line:gmatch("%[(%d+):(%d+)%.?(%d*)%]([^%[]*)") do
            local mn = tonumber(min) or 0
            local sc = tonumber(sec) or 0
            local hn = tonumber(hun) or 0
            local totalSec = mn * 60 + sc + (hn / 100)
            table.insert(MP.lyricsLines, {time = totalSec, text = trimStrGlobal(text)})
        end
    end
    f:close()
    table.sort(MP.lyricsLines, function(a, b) return a.time < b.time end)
end

function MP.getCurrentLyricLine(elapsedMs)
    if #MP.lyricsLines == 0 then return nil end
    local elapsedSec = (elapsedMs or 0) / 1000
    local current = nil
    for _, line in ipairs(MP.lyricsLines) do
        if line.time <= elapsedSec then
            current = line.text
        else
            break
        end
    end
    return current
end

function MP.scanMusic()
    MP.allSongs = {}
    pcall(function()
        local resolver = this.getContentResolver()
        local uri = MediaStore.Audio.Media.EXTERNAL_CONTENT_URI
        local projection = {"title", "artist", "duration", "_data"}
        local selection = MediaStore.Audio.Media.IS_MUSIC .. " != 0"
        local cursor = resolver.query(uri, projection, selection, nil, MediaStore.Audio.Media.TITLE .. " ASC")
        if cursor ~= nil then
            while cursor.moveToNext() do
                local title = cursor.getString(cursor.getColumnIndex("title"))
                local artist = cursor.getString(cursor.getColumnIndex("artist"))
                local duration = cursor.getLong(cursor.getColumnIndex("duration"))
                local path = cursor.getString(cursor.getColumnIndex("_data"))
                table.insert(MP.allSongs, {title = title, artist = artist, duration = duration, path = path})
            end
            cursor.close()
        end
    end)
    MP.songs = MP.allSongs
    return #MP.allSongs
end

function MP.applyEqualizer()
    if MP.equalizer ~= nil then
        pcall(function() MP.equalizer.release() end)
        MP.equalizer = nil
    end
    if MP.player ~= nil then
        local ok, eq = pcall(function() return Equalizer(0, MP.player.getAudioSessionId()) end)
        if ok and eq ~= nil then
            MP.equalizer = eq
            if MP.eqPresetIndex >= 0 then
                -- Kuch devices par preset lagane se pehle Equalizer enable karna zaroori hai,
                -- lekin kuch par preset PEHLE lagana zaroori hai — dono order try karte hain
                pcall(function()
                    MP.equalizer.usePreset(MP.eqPresetIndex)
                    MP.equalizer.setEnabled(true)
                end)
            else
                pcall(function() MP.equalizer.setEnabled(false) end)
            end
        end
    end
    MP.reassertPauseState()
end

-- Echo (PresetReverb, jaise mosque/hall wali double-triple awaz) aur Bass Boost
function MP.applySoundEffects()
    if MP.presetReverb ~= nil then
        pcall(function() MP.presetReverb.release() end)
        MP.presetReverb = nil
    end
    if MP.bassBoost ~= nil then
        pcall(function() MP.bassBoost.release() end)
        MP.bassBoost = nil
    end
    if MP.player == nil then return end
    local sessionId = MP.player.getAudioSessionId()

    if MP.echoPreset >= 0 then
        local ok, pr = pcall(function() return PresetReverb(0, sessionId) end)
        if ok and pr ~= nil then
            MP.presetReverb = pr
            pcall(function()
                MP.presetReverb.setPreset(MP.echoPreset)
                MP.presetReverb.setEnabled(true)
                -- PresetReverb ek "auxiliary" effect hai — sirf banane se kaam nahi chalta,
                -- player ki awaz is se explicitly route (attach) karni parti hai, warna
                -- effect on hokar bhi sunayi nahi deta.
                MP.player.attachAuxEffect(MP.presetReverb.getId())
                MP.player.setAuxEffectSendLevel(1.0)
            end)
        end
    else
        pcall(function() MP.player.setAuxEffectSendLevel(0.0) end)
    end

    if MP.bassBoostOn then
        local ok2, bb = pcall(function() return BassBoost(0, sessionId) end)
        if ok2 and bb ~= nil then
            MP.bassBoost = bb
            pcall(function()
                -- Kuch devices/headphones Bass Boost support hi nahi karte — is check ke
                -- bawajood bhi hum lagane ki koshish karte hain (kuch devices galat False
                -- report karte hain), bas crash nahi hone dete
                local supported = true
                pcall(function() supported = MP.bassBoost.getStrengthSupported() end)
                MP.bassBoost.setStrength(900)
                MP.bassBoost.setEnabled(true)
            end)
        end
    end

    MP.reassertPauseState()
end

-- Kuch devices par gaana start hote hi turant Equalizer/Bass Boost lagane se asar nahi hota
-- (audio session abhi poori tarah "ready" nahi hota) — thodi der baad dobara laga dete hain
-- taake pakka apply ho jaye
function MP.reapplyEffectsDelayed()
    pcall(function()
        seekProgress.postDelayed(function()
            MP.applyEqualizer()
            MP.applySoundEffects()
        end, 350)
    end)
end

function MP.playIndex(idx)
    if #MP.songs == 0 then
        service.speak("Koi gaana nahi mila, pehle scan karein")
        return
    end
    if idx < 1 then idx = #MP.songs end
    if idx > #MP.songs then idx = 1 end
    MP.currentIndex = idx
    local song = MP.songs[idx]

    if MP.player ~= nil then
        MP.player.stop()
        MP.player.release()
        MP.player = nil
    end

    MP.player = MediaPlayer()
    MP.player.reset()
    MP.player.setDataSource(song.path)
    MP.player.prepare()
    MP.player.setVolume(MP.volume, MP.volume)
    MP.player.start()
    MP.isPlaying = true

    MP.player.setOnCompletionListener(luajava.createProxy(
        "android.media.MediaPlayer$OnCompletionListener",
        { onCompletion = function(mp) MP.onSongComplete() end }
    ))

    MP.applyEqualizer()
    MP.applySoundEffects()
    MP.reapplyEffectsDelayed()
    MP.parseLrcForSong(song.path)
    MP.addRecent(song.path)
    if MP.onSongChangedUI then MP.onSongChangedUI() end
    service.speak((song.title or "Unknown") .. " - " .. (song.artist or "Unknown Artist"))
end

function MP.onSongComplete()
    if MP.repeatMode == "one" then
        MP.playIndex(MP.currentIndex)
    elseif MP.shuffle then
        math.randomseed(os.time())
        MP.playIndex(math.random(1, #MP.songs))
    elseif MP.repeatMode == "all" then
        MP.playIndex(MP.currentIndex + 1)
    else
        if MP.currentIndex < #MP.songs then
            MP.playIndex(MP.currentIndex + 1)
        else
            MP.isPlaying = false
            service.speak("Playlist khatam ho gayi")
        end
    end
end

function MP.togglePlayPause()
    if MP.player == nil then
        if #MP.songs > 0 then MP.playIndex(1) end
        return
    end
    if MP.isPlaying then
        MP.player.pause()
        MP.isPlaying = false
        service.speak("Pause")
    else
        MP.player.start()
        MP.isPlaying = true
        service.speak("Play")
    end
end

