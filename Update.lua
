        updateSkipLabels()
        seekVolume.setProgress(100)
        spinnerShuffle.setSelection(0)
        spinnerRepeat.setSelection(0)
        spinnerSpeed.setSelection(2)
        spinnerSkip.setSelection(1)
        spinnerEq.setSelection(0)
        spinnerEcho.setSelection(0)
        spinnerBass.setSelection(0)
