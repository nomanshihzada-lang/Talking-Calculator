            local folderSet = {}
            local folderList = {}
            for _, s in ipairs(MP.allSongs) do
                if s.path then
                    local dir = s.path:match("(.+)/[^/]+$")
                    if dir and not folderSet[dir] then
                        folderSet[dir] = true
                        table.insert(folderList, dir)
                    end
                end
            end
            table.sort(folderList)
            local folderNames = {}
            for _, dir in ipairs(folderList) do
