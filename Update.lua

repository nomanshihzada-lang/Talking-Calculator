function MP.exportBackup()
    local f = io.open(MP.backupPath, "w")
    if not f then return false end

    f:write("[SETTINGS]\n")
    f:write("repeatMode=" .. MP.repeatMode .. "\n")
    f:write("shuffle=" .. tostring(MP.shuffle) .. "\n")
    f:write("volume=" .. tostring(MP.volume) .. "\n")
    f:write("speed=" .. tostring(MP.speed) .. "\n")
    f:write("skipMs=" .. tostring(MP.skipMs) .. "\n")
    f:write("eqPresetIndex=" .. tostring(MP.eqPresetIndex) .. "\n")
    f:write("echoPreset=" .. tostring(MP.echoPreset) .. "\n")
    f:write("bassBoostOn=" .. tostring(MP.bassBoostOn) .. "\n")

    f:write("[PLAYLISTS]\n")
    for name, paths in pairs(MP.playlists) do
        f:write(name .. "|" .. table.concat(paths, "\1") .. "\n")
    end

    f:write("[FAVORITES]\n")
    for _, path in ipairs(MP.favorites) do
        f:write(path .. "\n")
    end

    f:write("[RECENT]\n")
    for _, path in ipairs(MP.recentlyPlayed) do
        f:write(path .. "\n")
    end

    f:close()
    return true
end

function MP.importBackup()
    local f = io.open(MP.backupPath, "r")
    if not f then return false end

    local section = nil
    MP.playlists = {}
    MP.favorites = {}
    MP.recentlyPlayed = {}

    for line in f:lines() do
        if line == "[SETTINGS]" or line == "[PLAYLISTS]" or line == "[FAVORITES]" or line == "[RECENT]" then
            section = line
        elseif section == "[SETTINGS]" then
            local k, v = line:match("^(%a+)=(.+)$")
            if k == "repeatMode" then MP.repeatMode = v
            elseif k == "shuffle" then MP.shuffle = (v == "true")
            elseif k == "volume" then MP.volume = tonumber(v) or 1.0
            elseif k == "speed" then MP.speed = tonumber(v) or 1.0
            elseif k == "skipMs" then MP.skipMs = tonumber(v) or 10000
            elseif k == "eqPresetIndex" then MP.eqPresetIndex = tonumber(v) or -1
            elseif k == "echoPreset" then MP.echoPreset = tonumber(v) or -1
            elseif k == "bassBoostOn" then MP.bassBoostOn = (v == "true")
            end
        elseif section == "[PLAYLISTS]" then
            local name, list = line:match("^(.-)|(.*)$")
            if name then
                local paths = {}
                for p in (list .. "\1"):gmatch("(.-)\1") do
                    if p ~= "" then table.insert(paths, p) end
                end
                MP.playlists[name] = paths
            end
        elseif section == "[FAVORITES]" then
            if line ~= "" then table.insert(MP.favorites, line) end
        elseif section == "[RECENT]" then
            if line ~= "" then table.insert(MP.recentlyPlayed, line) end
        end
    end
    f:close()

    MP.saveSettings()
    MP.savePlaylists()
    MP.saveFavorites()
    MP.saveRecent()
    return true
end

