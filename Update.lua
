  elseif fromU == "Pound-force (lbf)" then n = val * 4.44822 end

  if toU == "Kilonewtons (kN)" then return n / 1000
  elseif toU == "Gram-force (gf)" then return n / 0.00980665
  elseif toU == "Kilogram-force (kgf)" then return n / 9.80665
  elseif toU == "Pound-force (lbf)" then return n / 4.44822
  else return n end
end

