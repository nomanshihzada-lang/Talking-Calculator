-- Robust Dynamic Text-To-Speech Engine Manager
local ttsEngine

local function initTtsWithEngine(enginePackage)
  if ttsEngine then
    pcall(function() ttsEngine.shutdown() end)
  end

  local initListener = TextToSpeech.OnInitListener{
    onInit = function(status)
      if status == TextToSpeech.SUCCESS then
        ttsEngine.setLanguage(Locale.getDefault())
        ttsEngine.setSpeechRate(settingSpeechRate)
        ttsEngine.speak("Talking Calculator Ready. Created by Hafiz Zeeshan", TextToSpeech.QUEUE_FLUSH, nil)
      end
    end
  }

  if enginePackage and enginePackage ~= "" then
    ttsEngine = TextToSpeech(activity, initListener, enginePackage)
  else
    ttsEngine = TextToSpeech(activity, initListener)
  end
end

-- Fetch all Installed TTS Engines on the Device
local function fetchAvailableTtsEngines()
  installedTtsEngines = {}
  installedTtsEngineNames = {}

  pcall(function()
    local dummyTts
    dummyTts = TextToSpeech(activity, TextToSpeech.OnInitListener{
      onInit = function(status)
        if status == TextToSpeech.SUCCESS then
          local engines = dummyTts.getEngines()
          if engines then
            local iterator = engines.iterator()
            while iterator.hasNext() do
              local engineInfo = iterator.next()
              table.insert(installedTtsEngines, tostring(engineInfo.name))
              table.insert(installedTtsEngineNames, tostring(engineInfo.label))
            end
          end
          dummyTts.shutdown()
        end
      end
    })
  end)

  if #installedTtsEngineNames == 0 then
    table.insert(installedTtsEngineNames, "Default System TTS")
    table.insert(installedTtsEngines, "")
  end
end

