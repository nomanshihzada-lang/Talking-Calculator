local crossfadeTimerToken = 0

-- Ek gaana khatam hone se MP.crossfadeSec second pehle agla gaana dheere dheere shuru kar deta
-- hai, purane ki awaz kam hote hote aur naye ki awaz badhte badhte — dono overlap hote hain
local function startCrossfade()
    if MP.isCrossfading or #MP.songs == 0 or MP.player == nil then return end
    local nextIdx = MP.currentIndex + 1
    if nextIdx > #MP.songs then
        if MP.repeatMode == "all" then nextIdx = 1 else return end
    end
    local nextSong = MP.songs[nextIdx]
    if not nextSong then return end

    MP.isCrossfading = true
    crossfadeTimerToken = crossfadeTimerToken + 1
    local myToken = crossfadeTimerToken
    local oldPlayer = MP.player

    -- Purane player ka completion listener hata dein taake wo khud MP.onSongComplete ko
    -- dobara na bula de (hum manually switch kar rahe hain)
    pcall(function() oldPlayer.setOnCompletionListener(nil) end)

    local newPlayer = nil
    local ok = pcall(function()
        newPlayer = MediaPlayer()
        newPlayer.reset()
        newPlayer.setDataSource(nextSong.path)
        newPlayer.prepare()
        newPlayer.setVolume(0, 0)
        newPlayer.start()
    end)
    if not ok or newPlayer == nil then
        MP.isCrossfading = false
        return
    end

    local steps = 10
    local stepMs = math.floor((MP.crossfadeSec * 1000) / steps)
    local stepNum = 0

    local function fadeStep()
        if myToken ~= crossfadeTimerToken then return end
        stepNum = stepNum + 1
        local ratio = stepNum / steps
        pcall(function()
            oldPlayer.setVolume(MP.volume * (1 - ratio), MP.volume * (1 - ratio))
            newPlayer.setVolume(MP.volume * ratio, MP.volume * ratio)
        end)
        if stepNum < steps then
            seekProgress.postDelayed(fadeStep, stepMs)
        else
            pcall(function() oldPlayer.stop() end)
            pcall(function() oldPlayer.release() end)
            MP.player = newPlayer
            MP.currentIndex = nextIdx
            MP.isPlaying = true
            pcall(function()
                MP.player.setOnCompletionListener(luajava.createProxy(
                    "android.media.MediaPlayer$OnCompletionListener",
                    { onCompletion = function(mp) MP.onSongComplete() end }
                ))
            end)
            MP.applyEqualizer()
            MP.applySoundEffects()
            MP.reapplyEffectsDelayed()
            MP.parseLrcForSong(nextSong.path)
            MP.addRecent(nextSong.path)
            MP.abPointA = nil
            MP.abPointB = nil
            MP.abRepeatOn = false
            updateSongLabel()
            updatePlayPauseLabel()
            MP.isCrossfading = false
        end
    end
    fadeStep()
end

local function progressLoop()
    -- User tool ke bahar chala jaye (home dabaye, koi aur app kholein, waghera) to gaana
    -- khud-ba-khud ruk jana chahiye — har second check karte hain ke app ki window abhi
    -- foreground mein hai ya nahi
    local hasFocusOk, hasFocus = pcall(function() return activity.hasWindowFocus() end)
    if hasFocusOk and not hasFocus and MP.isPlaying then
        pcall(function() MP.player.pause() end)
        MP.isPlaying = false
        pcall(updatePlayPauseLabel)
    end

    if MP.player ~= nil and MP.isPlaying then
        local ok1, cur = pcall(function() return MP.player.getCurrentPosition() end)
        local ok2, dur = pcall(function() return MP.player.getDuration() end)
        if ok1 and ok2 then
            seekProgress.setMax(dur)
            seekProgress.setProgress(cur)
            txtTime.setText(MP.formatTime(cur) .. " / " .. MP.formatTime(dur))
            local lyricLine = MP.getCurrentLyricLine(cur)
            txtLyric.setText(lyricLine or "")

            -- A-B Repeat: Point B tak pahunchte hi wapas Point A par
            if MP.abRepeatOn and MP.abPointA and MP.abPointB and cur >= MP.abPointB then
                MP.seekTo(MP.abPointA)
            end

            -- Crossfade: gaana khatam hone se thodi der pehle agla shuru kar dein
            if MP.crossfadeOn and not MP.isCrossfading and not MP.abRepeatOn
               and dur > 0 and (dur - cur) <= (MP.crossfadeSec * 1000) and (dur - cur) > 300 then
                startCrossfade()
            end
        end
    else
        -- Watchdog: agar humne pause kiya hua tha lekin audio hardware ne (kisi bhi wajah se,
        -- jaise Equalizer/Echo attach hone se) khud track resume kar diya, to har second yahan
        -- check ho ke turant wapas pause ho jayega
        MP.reassertPauseState()
    end
    seekProgress.postDelayed(progressLoop, 1000)
end
