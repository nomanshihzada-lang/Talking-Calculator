-- ===== Sleep Timer helper =====
local function scheduleSleepTimer(minutes)
    MP.sleepTimerToken = MP.sleepTimerToken + 1
    local myToken = MP.sleepTimerToken
    service.speak(minutes .. " minute ke baad music band ho jayegi")
    seekProgress.postDelayed(function()
        if myToken == MP.sleepTimerToken and MP.player ~= nil and MP.isPlaying then
            MP.togglePlayPause()
            updatePlayPauseLabel()
            service.speak("Sleep timer khatam, music band")
        end
    end, minutes * 60000)
end

local function cancelSleepTimer()
    MP.sleepTimerToken = MP.sleepTimerToken + 1
end

