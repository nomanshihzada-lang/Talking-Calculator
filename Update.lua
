function MP.setSpeed(s)
    MP.speed = s
    if MP.player ~= nil then
        local ok = pcall(function()
            local params = MP.player.getPlaybackParams()
            params.setSpeed(s)
            MP.player.setPlaybackParams(params)
        end)
        if not ok then service.speak("Speed change is Android version par support nahi") end
    end
    MP.saveSettings()
end

function MP.formatTime(ms)
    local totalSec = math.floor((ms or 0) / 1000)
    local min = math.floor(totalSec / 60)
    local sec = totalSec % 60
    return string.format("%d:%02d", min, sec)
end

-- Kuch devices (jaise Samsung/Exynos audio hardware) par jab Equalizer/PresetReverb/BassBoost
-- ko chal rahe gaane ke real audio session se attach kiya jata hai, to audio hardware KHUD
-- track ko resume kar deta hai — chahe gaana pehle se pause ho. Yehi wajah thi ke Settings
-- ya Echo/Bass change karne par pause kiya hua gaana khud chalne lag jata tha. Ye function
-- MP.isPlaying (jo hamara asal, intended state hai) ke mutabiq wapas pause kar deta hai —
-- is se ye OS-level side effect hamesha cancel ho jayega.
function MP.reassertPauseState()
    if MP.player ~= nil and not MP.isPlaying then
        pcall(function()
            if MP.player.isPlaying() then
                MP.player.pause()
            end
        end)
    end
end

