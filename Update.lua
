-- Advanced Unit Converter Logics
local function convertLength(val, fromU, toU)
  local meters = val
  if fromU == "Kilometers" then meters = val * 1000
  elseif fromU == "Centimeters" then meters = val / 100
  elseif fromU == "Millimeters" then meters = val / 1000
  elseif fromU == "Inches" then meters = val * 0.0254
  elseif fromU == "Feet" then meters = val * 0.3048
  elseif fromU == "Yards" then meters = val * 0.9144
  end

  if toU == "Kilometers" then return meters / 1000
  elseif toU == "Centimeters" then return meters * 100
  elseif toU == "Millimeters" then return meters * 1000
  elseif toU == "Inches" then return meters / 0.0254
  elseif toU == "Feet" then return meters / 0.3048
  elseif toU == "Yards" then return meters / 0.9144
  else return meters end
end

local function convertWeight(val, fromU, toU)
  local kg = val
  if fromU == "Grams" then kg = val / 1000
  elseif fromU == "Milligrams" then kg = val / 1000000
  elseif fromU == "Pounds" then kg = val / 2.20462
  elseif fromU == "Ounces" then kg = val / 35.274
  end

  if toU == "Grams" then return kg * 1000
  elseif toU == "Milligrams" then return kg * 1000000
  elseif toU == "Pounds" then return kg * 2.20462
  elseif toU == "Ounces" then return kg * 35.274
  else return kg end
end

local function convertTemp(val, fromU, toU)
  if fromU == toU then return val end
  local celsius = val
  if fromU == "Fahrenheit" then celsius = (val - 32) * 5/9
  elseif fromU == "Kelvin" then celsius = val - 273.15
  end

  if toU == "Fahrenheit" then return (celsius * 9/5) + 32
  elseif toU == "Kelvin" then return celsius + 273.15
  else return celsius end
end

local function convertArea(val, fromU, toU)
  local sqMeters = val
  if fromU == "Square Kilometers" then sqMeters = val * 1000000
  elseif fromU == "Square Feet" then sqMeters = val * 0.092903
  elseif fromU == "Square Inches" then sqMeters = val * 0.00064516
  elseif fromU == "Acres" then sqMeters = val * 4046.86
  end

  if toU == "Square Kilometers" then return sqMeters / 1000000
  elseif toU == "Square Feet" then return sqMeters / 0.092903
  elseif toU == "Square Inches" then return sqMeters / 0.00064516
  elseif toU == "Acres" then return sqMeters / 4046.86
  else return sqMeters end
end

local function convertData(val, fromU, toU)
  local mb = val
  if fromU == "Kilobytes (KB)" then mb = val / 1024
  elseif fromU == "Gigabytes (GB)" then mb = val * 1024
  elseif fromU == "Terabytes (TB)" then mb = val * 1024 * 1024
  elseif fromU == "Bytes" then mb = val / (1024 * 1024)
  end

  if toU == "Kilobytes (KB)" then return mb * 1024
  elseif toU == "Gigabytes (GB)" then return mb / 1024
  elseif toU == "Terabytes (TB)" then return mb / (1024 * 1024)
  elseif toU == "Bytes" then return mb * (1024 * 1024)
  else return mb end
end

local function convertSpeed(val, fromU, toU)
  local kmh = val
  if fromU == "Meters/Sec (m/s)" then kmh = val * 3.6
  elseif fromU == "Miles/Hour (mph)" then kmh = val * 1.60934
  elseif fromU == "Knots" then kmh = val * 1.852
  end

  if toU == "Meters/Sec (m/s)" then return kmh / 3.6
  elseif toU == "Miles/Hour (mph)" then return kmh / 1.60934
  elseif toU == "Knots" then return kmh / 1.852
  else return kmh end
end

local function convertTime(val, fromU, toU)
  local sec = val
  if fromU == "Minutes" then sec = val * 60
  elseif fromU == "Hours" then sec = val * 3600
  elseif fromU == "Days" then sec = val * 86400
  end

  if toU == "Minutes" then return sec / 60
  elseif toU == "Hours" then return sec / 3600
  elseif toU == "Days" then return sec / 86400
  else return sec end
end

local function convertVolume(val, fromU, toU)
  local ml = val
  if fromU == "Liters" then ml = val * 1000
  elseif fromU == "US Gallons" then ml = val * 3785.41
  end

  if toU == "Liters" then return ml / 1000
  elseif toU == "US Gallons" then return ml / 3785.41
  else return ml end
end

