local function speakText(txt)
  if ttsEngine then
    local speechStr = tostring(txt)
    speechStr = speechStr:gsub("%+", " plus ")
    speechStr = speechStr:gsub("%-", " minus ")
    speechStr = speechStr:gsub("%*", " multiplied by ")
    speechStr = speechStr:gsub("/", " divided by ")
    speechStr = speechStr:gsub("=", " equals ")
    speechStr = speechStr:gsub("%%", " percent ")
    speechStr = speechStr:gsub("%.", " point ")
    speechStr = speechStr:gsub("C", " clear ")
    speechStr = speechStr:gsub("⌫", " backspace ")
    
    ttsEngine.setSpeechRate(settingSpeechRate)
    ttsEngine.speak(speechStr, TextToSpeech.QUEUE_FLUSH, nil)
  end
end

