      local m2 = cal.get(Calendar.MONTH) + 1 -- Java Calendar months are 0-based
      local d2 = cal.get(Calendar.DAY_OF_MONTH)

      local resY = y2 - y1
      local resM = m2 - m1
      local resD = d2 - d1

      if resD < 0 then
          resM = resM - 1
          local prevMonth = m2 - 1
          if prevMonth == 0 then prevMonth = 12 end
          local daysInPrevMonth = 31
          if prevMonth == 4 or prevMonth == 6 or prevMonth == 9 or prevMonth == 11 then 
              daysInPrevMonth = 30
          elseif prevMonth == 2 then
            if (y2 % 4 == 0 and y2 % 100 ~= 0) or (y2 % 400 == 0) then daysInPrevMonth = 29 else daysInPrevMonth = 28 end
          end
          resD = resD + daysInPrevMonth
      end
      
      if resM < 0 then
          resY = resY - 1
          resM = resM + 12
      end

      if resY < 0 then
         outputEdit.setText("")
         speakText("Birth year cannot be in the future!")
         return
      end

      local resultStr = resY .. " Years, " .. resM .. " Months, " .. resD .. " Days"
      outputEdit.setText(resultStr)
      table.insert(historyLog, "DOB: " .. d1 .. "/" .. m1 .. "/" .. y1 .. " = Age: " .. resultStr)
      speakText("Your exact age is " .. resultStr)
    end
  })

  dlg.getButton(DialogInterface.BUTTON_NEGATIVE).setOnClickListener(View.OnClickListener{
    onClick = function()
      local currentRes = outputEdit.getText().toString()
      if currentRes == "" then
        copyToClipboard("")
      else
        copyToClipboard(currentRes)
      end
    end
  })
end


