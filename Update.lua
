-- Core Auto-Calculation Logic
local function processCalculation()
  if currentInput == "" then return end
  
  if currentMode == "Basic" then
    local expression = currentInput:gsub("%%", "/100")
    expression = expression:gsub("sin", "math.sin")
    expression = expression:gsub("cos", "math.cos")
    expression = expression:gsub("tan", "math.tan")
    expression = expression:gsub("sqrt", "math.sqrt")
    expression = expression:gsub("log", "math.log10")

    local compiledFunc, loadErr = load("return " .. expression)
    if compiledFunc then
      local successFlag, calculationResult = pcall(compiledFunc)
      if successFlag and calculationResult then
        local finalStr = tostring(calculationResult)
        displayResultDialog(finalStr)
        currentInput = finalStr
      else
        displayResultDialog("Error")
      end
    else
      displayResultDialog("Invalid Expression")
    end
    
  elseif currentMode == "Length" then
    local numericVal = tonumber(currentInput)
    if numericVal then
      local outputVal = convertLength(numericVal, unitFrom, unitTo)
      local resString = string.format("%.4f", outputVal):gsub("%.0+$", "") .. " " .. unitTo
      displayResultDialog(resString)
      currentInput = tostring(outputVal)
    else displayResultDialog("Enter valid number") end
    
  elseif currentMode == "Weight" then
    local numericVal = tonumber(currentInput)
    if numericVal then
      local outputVal = convertWeight(numericVal, unitFrom, unitTo)
      local resString = string.format("%.4f", outputVal):gsub("%.0+$", "") .. " " .. unitTo
      displayResultDialog(resString)
      currentInput = tostring(outputVal)
    else displayResultDialog("Enter valid number") end
    
  elseif currentMode == "Temp" then
    local numericVal = tonumber(currentInput)
    if numericVal then
      local outputVal = convertTemp(numericVal, unitFrom, unitTo)
      local resString = string.format("%.2f", outputVal):gsub("%.0+$", "") .. " " .. unitTo
      displayResultDialog(resString)
      currentInput = tostring(outputVal)
    else displayResultDialog("Enter valid number") end

  elseif currentMode == "Area" then
    local numericVal = tonumber(currentInput)
    if numericVal then
      local outputVal = convertArea(numericVal, unitFrom, unitTo)
      local resString = string.format("%.4f", outputVal):gsub("%.0+$", "") .. " " .. unitTo
      displayResultDialog(resString)
      currentInput = tostring(outputVal)
    else displayResultDialog("Enter valid number") end

  elseif currentMode == "Data" then
    local numericVal = tonumber(currentInput)
    if numericVal then
      local outputVal = convertData(numericVal, unitFrom, unitTo)
      local resString = string.format("%.4f", outputVal):gsub("%.0+$", "") .. " " .. unitTo
      displayResultDialog(resString)
      currentInput = tostring(outputVal)
    else displayResultDialog("Enter valid number") end

  elseif currentMode == "Speed" then
    local numericVal = tonumber(currentInput)
    if numericVal then
      local outputVal = convertSpeed(numericVal, unitFrom, unitTo)
      local resString = string.format("%.4f", outputVal):gsub("%.0+$", "") .. " " .. unitTo
      displayResultDialog(resString)
      currentInput = tostring(outputVal)
    else displayResultDialog("Enter valid number") end

  elseif currentMode == "Time" then
    local numericVal = tonumber(currentInput)
    if numericVal then
      local outputVal = convertTime(numericVal, unitFrom, unitTo)
      local resString = string.format("%.4f", outputVal):gsub("%.0+$", "") .. " " .. unitTo
      displayResultDialog(resString)
      currentInput = tostring(outputVal)
    else displayResultDialog("Enter valid number") end

  elseif currentMode == "Volume" then
    local numericVal = tonumber(currentInput)
    if numericVal then
      local outputVal = convertVolume(numericVal, unitFrom, unitTo)
      local resString = string.format("%.4f", outputVal):gsub("%.0+$", "") .. " " .. unitTo
      displayResultDialog(resString)
      currentInput = tostring(outputVal)
    else displayResultDialog("Enter valid number") end
  end
end

