        onItemSelected = function(parent, view, position, id)
            MP.eqPresetIndex = position - 1
            MP.saveSettings()
            if MP.equalizer ~= nil then
                pcall(function()
                    if MP.eqPresetIndex >= 0 then
                        MP.equalizer.setEnabled(true)
                        MP.equalizer.usePreset(MP.eqPresetIndex)
                    else
                        MP.equalizer.setEnabled(false)
                    end
                end)
            end
        end,
        onNothingSelected = function(parent) end
    }))

