-- ===== Subtitles (.srt) =====
function VP.parseSrtForVideo(videoPath)
    VP.subtitleLines = {}
    VP.subtitleVideoPath = videoPath
    if not videoPath then return end
    local srtPath = videoPath:gsub("%.[%a%d]+$", ".srt")
    local f = io.open(srtPath, "r")
    if not f then return end
    local content = f:read("*a") or ""
    f:close()

    local function srtTimeToSec(h, m, s, ms)
        return tonumber(h) * 3600 + tonumber(m) * 60 + tonumber(s) + tonumber(ms) / 1000
    end

    for block in (content .. "\n\n"):gmatch("(.-)\n\r?\n") do
        local sh, sm, ss, sms, eh, em, es, ems, rest =
            block:match("(%d+):(%d+):(%d+)[,.](%d+)%s*%-%-%>%s*(%d+):(%d+):(%d+)[,.](%d+)\r?\n?(.*)")
        if sh then
            local startSec = srtTimeToSec(sh, sm, ss, sms)
            local endSec = srtTimeToSec(eh, em, es, ems)
            local text = trimStrGlobal((rest or ""):gsub("\r", ""):gsub("\n", " "))
            table.insert(VP.subtitleLines, {startSec = startSec, endSec = endSec, text = text})
        end
    end
    table.sort(VP.subtitleLines, function(a, b) return a.startSec < b.startSec end)
end

function VP.getCurrentSubtitleLine(elapsedMs)
    if #VP.subtitleLines == 0 then return nil end
    local elapsedSec = (elapsedMs or 0) / 1000
    for _, line in ipairs(VP.subtitleLines) do
        if elapsedSec >= line.startSec and elapsedSec <= line.endSec then
            return line.text
        end
    end
    return nil
end

function VP.scanVideos()
    VP.allVideos = {}
    local resolver = this.getContentResolver()
    local uri = MediaStore.Video.Media.EXTERNAL_CONTENT_URI
    local projection = {"title", "duration", "_data"}
    local cursor = resolver.query(uri, projection, nil, nil, MediaStore.Video.Media.TITLE .. " ASC")
    if cursor ~= nil then
        while cursor.moveToNext() do
            local title = cursor.getString(cursor.getColumnIndex("title"))
            local duration = cursor.getLong(cursor.getColumnIndex("duration"))
            local path = cursor.getString(cursor.getColumnIndex("_data"))
            table.insert(VP.allVideos, {title = title, duration = duration, path = path})
        end
        cursor.close()
    end
    VP.videos = VP.allVideos
    return #VP.allVideos
end

