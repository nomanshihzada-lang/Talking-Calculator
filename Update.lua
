-- ===== User Guide (Next / Previous, ek ek feature) =====
function MP.showGuidePage(idx)
    local items = MP.userGuideItems
    local total = #items
    if idx < 1 then idx = 1 end
    if idx > total then idx = total end
    local item = items[idx]

    local dlg = LuaDialog(this)
    dlg.setTitle("(" .. idx .. "/" .. total .. ") " .. item.title)
    dlg.setMessage(item.description)

    if idx < total then
        dlg.setButton("Next", function() MP.showGuidePage(idx + 1) end)
    else
        dlg.setButton("OK, Wapas Jayein", function() MP.showAboutSupport() end)
    end

    if idx > 1 then
        dlg.setButton2("Previous", function() MP.showGuidePage(idx - 1) end)
    else
        dlg.setButton2("Band Karein", function() MP.showAboutSupport() end)
    end

    dlg.show()
end

