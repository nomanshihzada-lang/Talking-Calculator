-- ===== Search Bar =====
-- NOTE: Pehle har letter type karne par buttons dynamically add/remove hote thay (TextWatcher se),
-- jo TalkBack ke accessibility node-tree ko confuse kar deta tha — isi wajah se neeche ke buttons
-- (jaise Settings) ka click kabhi-kabhi purane search-result button (jo song play karta hai) par
-- chala jata tha. Ab search ek dedicated "Search" button dabane par GridView dialog dikhata hai —
-- yehi reliable pattern Song List aur Playlists mein pehle se kaam kar raha hai.
-- Voice-to-text se query ke aage/peeche extra space aa jati hai, aur lambe titles mein "|" jaisi
-- punctuation exact match ko tod deti hai — is liye ab query aur title dono normalize (punctuation
-- hata ke, extra spaces theek karke) hote hain, aur agar poora text match na ho to bhi kam se kam
-- aadhe se zyada alfaz (words) mil jayein to gaana result mein aa jayega
local function normalizeText(s)
    s = s:lower()
    s = s:gsub("[^%w%s]", " ")
    s = s:gsub("%s+", " ")
    return trimStrGlobal(s)
end

btnSearchGo.onClick = function()
    local rawQuery = trimStrGlobal(txtSearch.getText().toString())
    if rawQuery == "" then
        service.speak("Pehle kuch search term likhein")
        return
    end
    if #MP.allSongs == 0 then
        service.speak("Pehle scan karein")
        return
    end

    service.speak("Search ho raha hai")

    runInBackground(function()
        local query = normalizeText(rawQuery)
        local queryWords = {}
        for w in query:gmatch("%S+") do
            if #w >= 2 then table.insert(queryWords, w) end
        end

        local matchTitles = {}
        local matchIndices = {}
        for i, s in ipairs(MP.allSongs) do
            if s.title then
                local normTitle = normalizeText(s.title)
                local matched = false
                if query ~= "" and normTitle:find(query, 1, true) then
                    matched = true
                elseif #queryWords > 0 then
                    local hitCount = 0
                    for _, w in ipairs(queryWords) do
                        if normTitle:find(w, 1, true) then hitCount = hitCount + 1 end
                    end
                    if hitCount >= math.max(1, math.ceil(#queryWords / 2)) then
                        matched = true
                    end
                end
                if matched then
                    table.insert(matchTitles, s.title)
                    table.insert(matchIndices, i)
                end
            end
        end

        runOnUiThread(function()
            -- Keyboard hide karein taake dialog saaf nazar aaye
            local imm = this.getSystemService("input_method")
            pcall(function() imm.hideSoftInputFromWindow(txtSearch.getWindowToken(), 0) end)

            if #matchTitles == 0 then
                service.speak("Koi gaana nahi mila")
                return
            end

            local gl = { GridView, id = "gridSearch", numColumns = 1, layout_width = "fill", layout_height = "fill" }
            local dlg = LuaDialog(this)
            dlg.View = loadlayout(gl)
            gridSearch.adapter = SingleLineAdapter(service, String(matchTitles))
            dlg.setTitle(#matchTitles .. " gaane mile")
            dlg.setButton("Cancel", nil)
            dlg.show()
            gridSearch.onItemClick = function(l, v)
                dlg.dismiss()
                for k, title in ipairs(matchTitles) do
                    if title == v.text then
                        MP.songs = MP.allSongs
                        MP.playIndex(matchIndices[k])
                        updateSongLabel()
                        updatePlayPauseLabel()
                        break
                    end
                end
                txtSearch.setText("")
            end
        end)
    end)
end

