-- Universal Screen Reader Native Announcer
local function speakText(txt)
  local speechStr = tostring(txt)
  speechStr = speechStr:gsub("%+", " plus ")
  speechStr = speechStr:gsub("%-", " minus ")
  speechStr = speechStr:gsub("%*", " multiplied by ")
  speechStr = speechStr:gsub("/", " divided by ")
  speechStr = speechStr:gsub("=", " equals ")
  speechStr = speechStr:gsub("%%", " percent ")
  speechStr = speechStr:gsub("%.", " point ")
  speechStr = speechStr:gsub("C", " clear ")
  speechStr = speechStr:gsub("⌫", " backspace ")
  
  pcall(function()
    activity.getWindow().getDecorView().announceForAccessibility(speechStr)
  end)
end

-- Clipboard Copy Helper
local function copyToClipboard(textToCopy)
  if textToCopy and textToCopy ~= "" and textToCopy ~= "\n" then
    local clipboard = activity.getSystemService(Context.CLIPBOARD_SERVICE)
    local clip = ClipData.newPlainText("Calculator Result", textToCopy)
    clipboard.setPrimaryClip(clip)
    speakText("Result copied to clipboard")
  else
    speakText("Nothing to copy yet")
  end
end

