-- Keypad Button Array Mapping
local buttonsCollection = {
  "1", "2", "3", "+",
  "4", "5", "6", "-",
  "7", "8", "9", "*",
  "0", ".", "/", "%",
  "C", "⌫", "🔊", "="
}

local keypadAdapter = ArrayAdapter(activity, android.R.layout.simple_list_item_1, buttonsCollection)
keypadGrid.setAdapter(keypadAdapter)

keypadGrid.setOnItemClickListener(AdapterView.OnItemClickListener{
  onItemClick = function(parent, view, position, id)
    triggerVibration()
    local pressedKey = buttonsCollection[position + 1]
    speakText(pressedKey)
    
    if pressedKey == "C" then
      currentInput = ""
      screenDisplay.setText("0")
    elseif pressedKey == "⌫" then
      if #currentInput > 0 then
        currentInput = currentInput:sub(1, -2)
        screenDisplay.setText(currentInput == "" and "0" or currentInput)
      end
    elseif pressedKey == "=" then
      processCalculation()
    elseif pressedKey == "🔊" then
      speakText(tostring(screenDisplay.getText()))
    else
      if tostring(screenDisplay.getText()) == "0" and pressedKey ~= "." then
        currentInput = pressedKey
      else
        currentInput = currentInput .. pressedKey
      end
      screenDisplay.setText(currentInput)
    end
  end
})

