-- Jab bhi app kuch bolta hai (service.speak), gaana/video ki awaz thodi der ke liye halki
-- kar dete hain taake screen-reader ki awaz saaf sunayi de, phir wapas normal volume par —
-- bilkul waisa hi jaisa reference code mein duckVolumeTemporarily karta tha
function MP.duckVolumeTemporarily(durationMs)
    if not MP.speechDuckingEnabled then return end
    pcall(function()
        if MP.player ~= nil then MP.player.setVolume(0.2, 0.2) end
    end)
    pcall(function()
        if VP.currentPlayerRef ~= nil then VP.currentPlayerRef.setVolume(0.2, 0.2) end
    end)
    MP.duckToken = MP.duckToken + 1
    local myToken = MP.duckToken
    pcall(function()
        seekProgress.postDelayed(function()
            if myToken == MP.duckToken then
                pcall(function()
                    if MP.player ~= nil then MP.player.setVolume(MP.volume, MP.volume) end
                end)
                pcall(function()
                    if VP.currentPlayerRef ~= nil then VP.currentPlayerRef.setVolume(1.0, 1.0) end
                end)
            end
        end, durationMs)
    end)
end

-- ===== Voice Pitch & Degree Speech =====
-- Reference code jaisa hi: dono ek hi PlaybackParams par pitch aur speed together lagate
-- hain, aur har tap par agli preset value par cycle karte hain
local pitchDegreeValues = {1.0, 1.125, 1.25, 1.375, 1.5}

function MP.applyVoicePitchSpeed()
    pcall(function()
        if MP.player ~= nil then
            local params = MP.player.getPlaybackParams()
            params.setPitch(MP.voicePitch)
            params.setSpeed(MP.voiceSpeedDegree)
            MP.player.setPlaybackParams(params)
        end
    end)
    pcall(function()
        if VP.currentPlayerRef ~= nil then
            local params = VP.currentPlayerRef.getPlaybackParams()
            params.setPitch(MP.voicePitch)
            params.setSpeed(MP.voiceSpeedDegree)
            VP.currentPlayerRef.setPlaybackParams(params)
        end
    end)
    MP.reassertPauseState()
end

function MP.cycleVoicePitch()
    MP.pitchIndex = MP.pitchIndex % #pitchDegreeValues + 1
    MP.voicePitch = pitchDegreeValues[MP.pitchIndex]
    MP.applyVoicePitchSpeed()
    service.speak("Voice pitch " .. MP.voicePitch)
end

function MP.cycleVoicePitchDown()
    MP.pitchIndex = MP.pitchIndex - 1
    if MP.pitchIndex < 1 then MP.pitchIndex = #pitchDegreeValues end
    MP.voicePitch = pitchDegreeValues[MP.pitchIndex]
    MP.applyVoicePitchSpeed()
    service.speak("Voice pitch " .. MP.voicePitch)
end

function MP.cycleDegreeSpeech()
    MP.speedDegreeIndex = MP.speedDegreeIndex % #pitchDegreeValues + 1
    MP.voiceSpeedDegree = pitchDegreeValues[MP.speedDegreeIndex]
    MP.applyVoicePitchSpeed()
    service.speak("Degree speech " .. MP.voiceSpeedDegree)
end

