    btnResetSettings.onClick = function()
        MP.repeatMode = "off"
        MP.shuffle = false
        MP.volume = 1.0
        MP.speed = 1.0
        MP.skipMs = 10000
        MP.eqPresetIndex = -1
        MP.echoPreset = -1
        MP.bassBoostOn = false
