  elseif fromU == "PSI" then pascal = val * 6894.76
  elseif fromU == "Atmosphere (atm)" then pascal = val * 101325 end

  if toU == "Bar" then return pascal / 100000
  elseif toU == "PSI" then return pascal / 6894.76
  elseif toU == "Atmosphere (atm)" then return pascal / 101325
  else return pascal end
end

local function convertEnergy(val, fromU, toU)
  local joules = val
  if fromU == "Calories (cal)" then joules = val * 4.184
  elseif fromU == "Kilocalories (kcal)" then joules = val * 4184
  elseif fromU == "Kilowatt-hours (kWh)" then joules = val * 3600000 end

  if toU == "Calories (cal)" then return joules / 4.184
  elseif toU == "Kilocalories (kcal)" then return joules / 4184
  elseif toU == "Kilowatt-hours (kWh)" then return joules / 3600000
  else return joules end
end

local function convertAngle(val, fromU, toU)
  local deg = val
  if fromU == "Radians" then deg = val * (180 / math.pi)
  elseif fromU == "Gradians" then deg = val * 0.9 end

  if toU == "Radians" then return deg * (math.pi / 180)
  elseif toU == "Gradians" then return deg / 0.9
  else return deg end
end

local function convertForce(val, fromU, toU)
